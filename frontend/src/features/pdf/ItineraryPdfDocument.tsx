// The Itinerary Export layout (frontend-spec §4.6). Loaded on demand with the PDF library.
// Text uses DejaVu Sans (see fonts.ts); call registerPdfFonts() before rendering.
import {
  type Activity,
  dayCount,
  diffDays,
  listTripDates,
  TRIP_TYPE_LABELS,
  type TripDetail,
  todayLocal,
} from '@sanchari/shared';
import { Document, Page, StyleSheet, Text, View } from '@react-pdf/renderer';
import { formatDate, formatLongDate, formatRange, pluralize } from '@/lib/format';
import { PDF_FONT } from './font-family';

// A4 in points. The footer is positioned from the top: `bottom` offsets don't render in react-pdf 4.
const PAGE_HEIGHT = 841.89;

const styles = StyleSheet.create({
  page: {
    paddingTop: 48,
    paddingBottom: 56,
    paddingHorizontal: 48,
    fontFamily: PDF_FONT,
    fontSize: 10.5,
    lineHeight: 1.4,
    color: '#111111',
    // No ligatures, so copied text keeps every letter ("flowing", not "fowing").
    fontFeatureSettings: { liga: false, clig: false },
  },
  title: { fontWeight: 'bold', fontSize: 22, lineHeight: 1.2, marginBottom: 6 },
  meta: { fontSize: 11, color: '#444444', marginBottom: 2 },
  sectionTitle: { fontWeight: 'bold', fontSize: 13, marginTop: 18, marginBottom: 6 },
  table: { borderTopWidth: 1, borderColor: '#dddddd' },
  row: { flexDirection: 'row', borderBottomWidth: 1, borderColor: '#dddddd', paddingVertical: 4 },
  headerCell: { fontWeight: 'bold' },
  colName: { width: '45%', paddingRight: 8 },
  colDates: { width: '35%', paddingRight: 8 },
  colNights: { width: '20%', textAlign: 'right' },
  day: { marginTop: 12 },
  dayTitle: { fontWeight: 'bold', fontSize: 11.5, marginBottom: 4 },
  activity: { flexDirection: 'row', marginBottom: 2 },
  activityNumber: { width: 22, color: '#666666' },
  activityText: { flex: 1 },
  empty: { color: '#777777' },
  footer: {
    position: 'absolute',
    top: PAGE_HEIGHT - 36,
    left: 48,
    right: 48,
    flexDirection: 'row',
    justifyContent: 'space-between',
    fontSize: 8.5,
    color: '#777777',
  },
});

function nightsLabel(start: string, end: string) {
  const nights = diffDays(start, end);
  return nights === 0 ? 'Day trip' : pluralize(nights, 'night');
}

export function ItineraryPdfDocument({ trip }: { trip: TripDetail }) {
  const days = listTripDates(trip.destinations);
  const byDate = Map.groupBy(trip.activities, (a: Activity) => a.date);
  const generatedOn = formatDate(todayLocal());
  const length = pluralize(dayCount(trip.startDate, trip.endDate), 'day');

  return (
    <Document title={`${trip.name} — Itinerary`} author="Sanchari" creator="Sanchari">
      <Page size="A4" style={styles.page}>
        {/* Footer on every page (fixed elements go first) */}
        <View style={styles.footer} fixed>
          <Text>Generated by Sanchari on {generatedOn}</Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
        </View>
        {/* 1. Title block */}
        <View>
          <Text style={styles.title}>{trip.name}</Text>
          <Text style={styles.meta}>
            {TRIP_TYPE_LABELS[trip.tripType]} trip · {formatRange(trip.startDate, trip.endDate)} ·{' '}
            {length}
          </Text>
        </View>

        {/* 2. Destinations table */}
        <Text style={styles.sectionTitle}>Destinations</Text>
        <View style={styles.table}>
          <View style={styles.row}>
            <Text style={[styles.colName, styles.headerCell]}>Destination</Text>
            <Text style={[styles.colDates, styles.headerCell]}>Dates</Text>
            <Text style={[styles.colNights, styles.headerCell]}>Nights</Text>
          </View>
          {trip.destinations.map((d) => (
            <View key={`${d.name}-${d.startDate}`} style={styles.row} wrap={false}>
              <Text style={styles.colName}>{d.name}</Text>
              <Text style={styles.colDates}>{formatRange(d.startDate, d.endDate)}</Text>
              <Text style={styles.colNights}>{nightsLabel(d.startDate, d.endDate)}</Text>
            </View>
          ))}
        </View>

        {/* 3. One section per Day */}
        <Text style={styles.sectionTitle}>Day by day</Text>
        {days.map((day) => {
          const activities = byDate.get(day.date) ?? [];
          const where = day.destinations.map((d) => d.name).join(' → ');
          return (
            <View key={day.date} style={styles.day}>
              {/* Keep a Day's title with at least its first lines on the same page. */}
              <Text style={styles.dayTitle} minPresenceAhead={36}>
                Day {day.dayNumber} — {formatLongDate(day.date)}
                {where ? ` — ${where}` : ''}
              </Text>
              {activities.length === 0 ? (
                <Text style={styles.empty}>No activities planned</Text>
              ) : (
                activities.map((a, i) => (
                  <View key={a.id} style={styles.activity} wrap={false}>
                    <Text style={styles.activityNumber}>{i + 1}.</Text>
                    <Text style={styles.activityText}>{a.text}</Text>
                  </View>
                ))
              )}
            </View>
          );
        })}
      </Page>
    </Document>
  );
}
